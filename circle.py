import math


def area(r):
    """
    Считает площадь круга по радиусу.

    Параметры:
        r (float): радиус круга.

    Возвращает:
        float: площадь круга (pi * r * r).

    Пример:
        area(2) -> 12.566370614359172
    """
    return math.pi * r * r


def perimeter(r):
    """
    Считает длину окружности по радиусу.

    Параметры:
        r (float): радиус окружности.

    Возвращает:
        float: длина окружности (2 * pi * r).

    Пример:
        perimeter(1) -> 6.283185307179586
    """
    return 2 * math.pi * r
