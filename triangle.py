def area(a, h):
    """
    Считает площадь треугольника по основанию и высоте.

    Параметры:
        a (float): основание треугольника.
        h (float): высота, опущенная на основание.

    Возвращает:
        float: площадь треугольника (a * h / 2).

    Пример:
        area(4, 3) -> 6.0
    """
    return a * h / 2


def perimeter(a, b, c):
    """
    Считает периметр треугольника по трём сторонам.

    Параметры:
        a (float): первая сторона.
        b (float): вторая сторона.
        c (float): третья сторона.

    Возвращает:
        float: периметр треугольника (a + b + c).

    Пример:
        perimeter(3, 4, 5) -> 12
    """
    return a + b + c
