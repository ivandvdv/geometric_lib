def area(a):
    """
    Считает площадь квадрата.

    Параметры:
        a (float): сторона квадрата.

    Возвращает:
        float: площадь квадрата (a * a).

    Пример:
        area(3) -> 9
    """
    return a * a


def perimeter(a):
    """
    Считает периметр квадрата.

    Параметры:
        a (float): сторона квадрата.

    Возвращает:
        float: периметр квадрата (4 * a).

    Пример:
        perimeter(3) -> 12
    """
    return 4 * a
