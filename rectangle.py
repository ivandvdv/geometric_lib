def area(a, b):
    """
    Считает площадь прямоугольника.

    Параметры:
        a (float): длина прямоугольника.
        b (float): ширина прямоугольника.

    Возвращает:
        float: площадь прямоугольника (a * b).

    Пример:
        area(2, 3) -> 6
    """
    return a * b


def perimeter(a, b):
    """
    Считает периметр прямоугольника.

    Параметры:
        a (float): длина прямоугольника.
        b (float): ширина прямоугольника.

    Возвращает:
        float: периметр прямоугольника (2 * (a + b)).

    Пример:
        perimeter(2, 3) -> 10
    """
    return 2 * (a + b)
